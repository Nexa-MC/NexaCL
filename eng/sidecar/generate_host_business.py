"""Generate general business routes from the reviewed, numeric Sidecar Host catalog."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(catalog="host-business.json"):
    spec = json.loads((ROOT / "eng/sidecar" / catalog).read_text())
    operations = spec['operations']
    if len({o['id'] for o in operations}) != len(operations) or len({o['semantic'] for o in operations}) != len(operations):
        raise ValueError('Duplicate Host business contract')
    fingerprint = hashlib.sha256(json.dumps(operations, sort_keys=True, separators=(',', ':')).encode()).hexdigest().upper()
    header = '// <auto-generated/>\n#nullable enable\n'
    client = [header, 'using Nexa.Sidecar.Host.Data;\nusing Nexa.Sidecar.Host.Wire;\nusing Nexa.Sidecar.Protocol;\nusing Nexa.Xsr;\nusing Nexa.Xsr.Runtime;\nnamespace Nexa.Sidecar.Host;\n\n',
              'public sealed partial class SidecarBusinessClient\n{\n    private void Register(XsrCommandRouterBuilder commands, XsrQueryRouterBuilder queries)\n    {\n']
    host = [header, 'using Nexa.Sidecar.Host.Wire;\nusing Nexa.Sidecar.Protocol;\nusing Nexa.Xsr;\nusing Nexa.Xsr.Runtime;\nnamespace Nexa.Services.Composition.Sidecars;\n\n',
            'public sealed partial class SidecarBusinessApi\n{\n    private IEnumerable<SidecarHostRequestRoute> CreateRoutes()\n    {\n']
    constants = [header, 'using Nexa.Xsr;\nnamespace Nexa.Sidecar.Host.Data;\n\n']
    owners = {}
    availability = ['        if (_state is not null && _authorize(caller, "host.state.read")) result.Add(254);\n']
    for op in operations:
        identifier, semantic = op['id'], op['semantic']
        query = op['kind'] == 'query'
        request, response = op['input'], op.get('output')
        target = 'queries' if query else 'commands'
        args = request + (', ' + response if query else '')
        client.append(f'        {target}.Register<{args}>(XsrSemanticId.Parse("{semantic}"), async (input, token) =>\n        {{\n')
        client.append(f'            using var writer = new ServiceWireWriter(); writer.{request}(input);\n            var reply = await Call({identifier}, {str(query).lower()}, writer.Finish(), token).ConfigureAwait(false);\n')
        if query:
            client.append(f'            if (!reply.Success) return XsrResult.Failure<{response}>(Error(reply.ErrorCode));\n            using var reader = new ServiceWireReader(reply.Value.ToArray());\n            if (ReadOutcome(reader) is {{ }} error) return XsrResult.Failure<{response}>(error);\n            var result = reader.{response}() ?? throw new InvalidDataException("Missing Host reply."); reader.End();\n            return XsrResult.Success(result);\n')
        else:
            client.append('            if (!reply.Success) return XsrResult.Failure(Error(reply.ErrorCode));\n            using var reader = new ServiceWireReader(reply.Value.ToArray());\n            var error = ReadOutcome(reader); reader.End();\n            return error is null ? XsrResult.Success() : XsrResult.Failure(error);\n')
        client.append('        });\n')
        caller_name = 'caller' if spec.get('sessionScoped') else '_'
        caller_argument = ', caller' if spec.get('sessionScoped') else ''
        host.append(f'        yield return new({identifier}, {str(query).lower()}, SidecarWireCodecs.GeneratedDto, SidecarWireCodecs.GeneratedDto, TimeSpan.FromMinutes(5),\n            caller => _authorize(caller, "{semantic}"), async ({caller_name}, bytes, token) =>\n        {{\n')
        host.append(f'            using var reader = new ServiceWireReader(bytes.ToArray()); var input = reader.{request}() ?? throw new InvalidDataException("Missing Host request."); reader.End();\n')
        host.append(f'            var router = {"Queries" if query else "Commands"}("{op["scope"]}"{caller_argument});\n            if (router is null || !router.TryResolve(global::{op["routeType"]}.{op["route"].split(".")[-1]}, out var route)) return XsrResult.Failure<SidecarBinaryValue>(XsrRuntimeErrors.RouteNotFound());\n')
        if query:
            host.append(f'            var result = await router.QueryAsync<global::{op["inputType"]}, global::{op["outputType"]}>(route, input, cancellationToken: token).ConfigureAwait(false);\n            using var writer = new ServiceWireWriter(); WriteOutcome(writer, result.Error);\n            if (result.IsSuccess) writer.{response}(result.Value);\n            return XsrResult.Success(new SidecarBinaryValue(SidecarWireCodecs.GeneratedDto, writer.Finish()));\n')
        else:
            host.append('            var result = await router.Dispatch(route, input, cancellationToken: token).Completion.ConfigureAwait(false);\n            using var writer = new ServiceWireWriter(); WriteOutcome(writer, result.Error);\n            return XsrResult.Success(new SidecarBinaryValue(SidecarWireCodecs.GeneratedDto, writer.Finish()));\n')
        host.append('        });\n')
        owner, field = op['route'].split('.')
        owners.setdefault(owner, []).append((field, semantic))
        availability.append(f'        if (_authorize(caller, "{semantic}") && {"Queries" if query else "Commands"}("{op["scope"]}"{caller_argument})?.TryResolve(global::{op["routeType"]}.{field}, out _) == true) result.Add({identifier});\n')
    client.append('    }\n    private const string CatalogFingerprint = "' + fingerprint + '";\n}\n')
    host.append('    }\n    private IReadOnlyList<uint> Available(SidecarHostCaller caller)\n    {\n        List<uint> result = [];\n' + ''.join(availability) + '        return result;\n    }\n    private const string CatalogFingerprint = "' + fingerprint + '";\n}\n')
    for owner, fields in sorted(owners.items()):
        constants.append('public static class ' + owner + '\n{\n')
        for field, semantic in sorted(fields):
            constants.append(f'    public static readonly XsrSemanticId {field} = XsrSemanticId.Parse("{semantic}");\n')
        constants.append('}\n\n')
    result = {
        'src/sidecar/Nexa.Sidecar.Host.Contracts/BusinessClient.Generated.cs': ''.join(client),
        'src/sidecar/Nexa.Sidecar.Host.Contracts/BusinessRoutes.Generated.cs': ''.join(constants),
        'src/app/Nexa.Services.Composition/Composition/Sidecars/BusinessApi.Generated.cs': ''.join(host),
    }

    if spec.get('extension'):
        # A new catalog has independent discovery, codecs and availability. Never
        # regenerate the frozen base schema merely to add an extension operation.
        extension = spec['extension']
        transformed = {}
        for relative, text in result.items():
            if 'BusinessApi' in relative:
                text = text.replace(availability[0], '')
            for old, new in (
                ('SidecarBusiness', 'Sidecar' + extension),
                ('Nexa.Sidecar.Host.Data', 'Nexa.Sidecar.Host.' + extension + '.Data'),
                ('Nexa.Sidecar.Host.Wire', 'Nexa.Sidecar.Host.' + extension + '.Wire'),
            ):
                text = text.replace(old, new)
            parent, name = relative.rsplit('/', 1)
            transformed[parent + '/' + extension + '/' + name] = text
        wire = '// <auto-generated/>\n#nullable enable\n' + (ROOT / 'src/sidecar/HostBusinessWire.cs').read_text().replace(
            'Nexa.Sidecar.Host.Wire', 'Nexa.Sidecar.Host.' + extension + '.Wire')
        transformed['src/sidecar/Nexa.Sidecar.Host.Contracts/' + extension + '/' + extension + 'Wire.Generated.cs'] = wire
        transformed['src/app/Nexa.Services.Composition/Composition/Sidecars/' + extension + '/' + extension + 'Wire.Generated.cs'] = wire
        return transformed
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true')
    parser.add_argument('--catalog', default='host-business.json')
    args = parser.parse_args()
    for relative, text in generate(args.catalog).items():
        path = ROOT / relative
        if args.verify:
            if not path.exists() or path.read_text() != text:
                raise SystemExit('Stale Host business binding: ' + relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
