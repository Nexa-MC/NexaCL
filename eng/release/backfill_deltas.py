"""Add an immutable signed delta extension to an existing full-only source release."""
import argparse
import os
import shutil
import tempfile
from pathlib import Path

from delta import INDEX_NAME, digest, generate, validate_index
from delta_history import fetch
from publish_updates import SOURCE, api, append_deltas, assets_for, gh, identity
from sign import sign_delta_extension, verify_signatures
from verify import expected_names


def backfill(tag, public_key, private_key, passphrase):
    version, channel = identity(tag)
    release = api(f"repos/{SOURCE}/releases/tags/{tag}")
    if (release.get("tag_name") != tag or release.get("draft") is not False
            or release.get("prerelease") is not (channel != "stable")):
        raise ValueError("Backfill requires an existing public source release")
    sizes = assets_for(release, tag)
    with tempfile.TemporaryDirectory(prefix="nexa-delta-backfill-") as temporary:
        root = Path(temporary)
        downloaded, packages, history = (root / name for name in ("downloaded", "packages", "history"))
        downloaded.mkdir()
        gh("release", "download", tag, "--repo", SOURCE, "--dir", downloaded)
        if ({p.name for p in downloaded.iterdir()} != set(sizes)
                or any(not p.is_file() or p.is_symlink() or p.stat().st_size != sizes[p.name] for p in downloaded.iterdir())):
            raise ValueError("Downloaded source assets differ from the release")
        if INDEX_NAME in sizes:
            verify_signatures(downloaded, version, public_key)
            print("The published differential index is already complete and immutable.")
            return False
        # A previous interrupted upload may have left undiscoverable bundle files.
        # Isolate the original signed distribution before generating any extension.
        base = expected_names(version) | {"SHA256SUMS", "Nexa-Release.json"}
        base |= {name + ".asc" for name in base}
        if not base <= sizes.keys():
            raise ValueError("Source full distribution is incomplete")
        packages.mkdir()
        for name in base:
            (downloaded / name).replace(packages / name)
        verify_signatures(packages, version, public_key)
        fetch(history, version)
        generate(packages, version, history)
        extension = validate_index(packages, version)
        if not extension:
            raise ValueError("No smaller authenticated differential package could be generated")
        allowed = extension | {name + ".asc" for name in extension}
        for path in downloaded.iterdir():
            if path.name not in allowed:
                raise ValueError("Unexpected partial differential asset")
            target = packages / path.name
            if path.name.endswith(".asc"):
                shutil.copyfile(path, target)
            elif path.stat().st_size != target.stat().st_size or digest(path) != digest(target):
                raise ValueError("Partial differential payload conflicts with generated bytes")
        sign_delta_extension(packages, version, public_key, private_key, passphrase)
        return append_deltas(SOURCE, tag, packages, version)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tag", required=True)
    args = parser.parse_args()
    private = os.environ.pop("GPG_PRIVATE_KEY", "")
    passphrase = os.environ.pop("GPG_PASSPHRASE", "")
    if not private.strip():
        raise ValueError("The existing publisher signing key is required")
    public = Path(__file__).resolve().parents[2].joinpath("GPG-PUBLIC-KEY.asc").read_bytes()
    backfill(args.tag, public, private, passphrase)


if __name__ == "__main__":
    main()
