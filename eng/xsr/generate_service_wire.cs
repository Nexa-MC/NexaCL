// Development-only reflection. Generated module codecs use numeric fields and no runtime reflection.
using System.Reflection;
using System.Runtime.Loader;
using System.Security.Cryptography;
using System.Text;

string assemblyPath = Path.GetFullPath(args[0]);
AssemblyLoadContext.Default.Resolving += (_, name) =>
{
    string path = Path.Combine(Path.GetDirectoryName(assemblyPath)!, name.Name + ".dll");
    return File.Exists(path) ? AssemblyLoadContext.Default.LoadFromAssemblyPath(path) : null;
};
Assembly assembly = AssemblyLoadContext.Default.LoadFromAssemblyPath(assemblyPath);
string[] roots = File.ReadAllLines(args[1]).Select(line => line.Trim()).Where(line => line.Length > 0 && !line.StartsWith('#')).ToArray();
var pending = new Queue<Type>(roots.Select(name =>
{
    int separator = name.IndexOf('|');
    Assembly owner = separator < 0 ? assembly : AssemblyLoadContext.Default.LoadFromAssemblyPath(
        Path.Combine(Path.GetDirectoryName(assemblyPath)!, name[..separator] + ".dll"));
    return owner.GetType(separator < 0 ? name : name[(separator + 1)..], throwOnError: true)!;
}));
var types = new Dictionary<string, Type>(StringComparer.Ordinal);
while (pending.TryDequeue(out var type))
{
    if (types.TryGetValue(Id(type), out var previous) && previous != type) throw new InvalidOperationException("Ambiguous DTO name: " + type);
    if (!types.TryAdd(Id(type), type) || Special(type)) continue;
    if (Nullable.GetUnderlyingType(type) is { } nullable) pending.Enqueue(nullable);
    else if (StringMap(type)) pending.Enqueue(typeof(string));
    else if (TypedMap(type)) { pending.Enqueue(type.GetGenericArguments()[0]); pending.Enqueue(type.GetGenericArguments()[1]); }
    else if (Element(type) is { } element) pending.Enqueue(element);
    else foreach (var property in Shape(type).Properties) pending.Enqueue(property.PropertyType);
}
var schema = new StringBuilder();
var code = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace " + args[3] + ";\n\n");
var nullability = new NullabilityInfoContext();
foreach (bool write in new[] { true, false })
{
    code.Append("internal sealed partial class ServiceWire" + (write ? "Writer" : "Reader") + "\n{\n");
    foreach (Type type in types.Values.OrderBy(Id, StringComparer.Ordinal)) Emit(type, write);
    code.Append("}\n\n");
}
string fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(schema.ToString().ReplaceLineEndings("\n"))));
code.Append("internal static class ServiceWireSchema\n{\n    internal const string Fingerprint = \"" + fingerprint + "\";\n}\n");
File.WriteAllText(args[2], code.ToString());
Console.WriteLine($"Generated {types.Count} service DTO shapes: {fingerprint}");
if (args.Length > 4) ExportSidecarContracts(args[4]);

void ExportSidecarContracts(string destination)
{
    const string dataNamespace = "Nexa.Sidecar.Host.Data";
    var contracts = types.Values.Where(t => t.IsEnum || !Special(t) && !t.IsGenericType && !t.IsArray)
        .OrderBy(Id, StringComparer.Ordinal).ToArray();
    string Rename(string text)
    {
        foreach (var type in contracts.OrderByDescending(t => Name(t).Length))
            text = text.Replace(Name(type), "global::" + dataNamespace + "." + Id(type), StringComparison.Ordinal);
        return text;
    }
    string FieldType(PropertyInfo property) => Rename(Name(property.PropertyType)) +
        (!property.PropertyType.IsValueType && nullability.Create(property).ReadState == NullabilityState.Nullable ? "?" : "");
    string Default(ParameterInfo parameter)
    {
        if (!parameter.HasDefaultValue) return "";
        object? value = parameter.DefaultValue;
        if (value is null) return " = default";
        if (parameter.ParameterType.IsEnum) return " = (" + Rename(Name(parameter.ParameterType)) + ")" + Convert.ToInt64(value);
        if (value is bool boolean) return boolean ? " = true" : " = false";
        if (value is string text) return " = " + System.Text.Json.JsonSerializer.Serialize(text);
        return " = " + Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture);
    }
    var output = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace " + dataNamespace + ";\n\n");
    foreach (var type in contracts)
    {
        if (type.IsEnum)
        {
            output.Append("public enum " + Id(type) + " : " + Name(Enum.GetUnderlyingType(type)) + "\n{\n");
            foreach (string name in Enum.GetNames(type))
                output.Append("    " + name + " = " + Convert.ToString(Convert.ChangeType(Enum.Parse(type, name), Enum.GetUnderlyingType(type)), System.Globalization.CultureInfo.InvariantCulture) + ",\n");
            output.Append("}\n\n");
            continue;
        }
        var shape = Shape(type);
        var constructor = type.GetConstructors().Single(c => c.GetParameters().Length == shape.Positional &&
            c.GetParameters().Select(p => p.Name).SequenceEqual(shape.Properties.Take(shape.Positional).Select(p => p.Name), StringComparer.OrdinalIgnoreCase));
        var parameters = constructor.GetParameters();
        output.Append("public " + (type.IsValueType ? "readonly record struct " : "sealed record ") + Id(type) + "(" +
            string.Join(", ", shape.Properties.Take(shape.Positional).Select((p, i) => FieldType(p) + " " + p.Name + Default(parameters[i]))) + ")\n{\n");
        foreach (var property in shape.Properties.Skip(shape.Positional))
            output.Append("    public required " + FieldType(property) + " " + property.Name + " { get; init; }\n");
        // Generated records may carry credential-bearing command inputs. Never synthesize
        // a record ToString that includes their fields in dispatch diagnostics.
        output.Append("    public override string ToString() => nameof(" + Id(type) + ");\n");
        output.Append("}\n\n");
    }
    Directory.CreateDirectory(destination);
    File.WriteAllText(Path.Combine(destination, "BusinessData.Generated.cs"), output.ToString());
    File.WriteAllText(Path.Combine(destination, "BusinessWire.Generated.cs"), Rename(code.ToString()));
}

static string Id(Type t) => t.IsGenericType ? t.Name.Split('`')[0] + "_" + string.Join('_', t.GetGenericArguments().Select(Id))
    : t.IsArray ? "Array_" + Id(t.GetElementType()!) : t.Name;
static string Name(Type t) => t.IsGenericType ? "global::" + t.GetGenericTypeDefinition().FullName!.Split('`')[0] + "<" + string.Join(", ", t.GetGenericArguments().Select(Name)) + ">"
    : t.IsArray ? Name(t.GetElementType()!) + "[]" : "global::" + t.FullName!.Replace('+', '.');
static bool Special(Type t) => t.IsPrimitive || t.IsEnum || t == typeof(string) || t == typeof(byte[])
    || t == typeof(Uri) || t == typeof(Guid) || t == typeof(DateTimeOffset) || t == typeof(TimeSpan) || t == typeof(Version)
    || t == typeof(ReadOnlyMemory<byte>) || t.FullName is "Nexa.Core.Media.PngImage" or "Nexa.Xsr.XsrSemanticId";
static Type? Element(Type t) => t.IsArray ? t.GetElementType() : t.IsGenericType && t.GetGenericTypeDefinition() == typeof(IReadOnlyList<>) ? t.GetGenericArguments()[0] : null;
static bool StringMap(Type t) => t == typeof(IReadOnlyDictionary<string, string>);
static bool TypedMap(Type t) => t.IsGenericType && t.GetGenericTypeDefinition() == typeof(IReadOnlyDictionary<,>)
    && (t.GetGenericArguments()[0] == typeof(string) || t.GetGenericArguments()[0].IsEnum);
static (PropertyInfo[] Properties, int Positional) Shape(Type t)
{
    var properties = t.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.GetIndexParameters().Length == 0).ToArray();
    var constructor = t.GetConstructors().Where(c => c.GetParameters().All(p => properties.Any(v => string.Equals(v.Name, p.Name, StringComparison.OrdinalIgnoreCase) && p.ParameterType.IsAssignableFrom(v.PropertyType))))
        .OrderByDescending(c => c.GetParameters().Length).FirstOrDefault() ?? throw new InvalidOperationException("No DTO constructor: " + t);
    var positional = constructor.GetParameters().Select(p => properties.Single(v => string.Equals(v.Name, p.Name, StringComparison.OrdinalIgnoreCase))).ToArray();
    return (positional.Concat(properties.Where(p => p.SetMethod is { IsPublic: true } && !positional.Contains(p)).OrderBy(p => p.Name, StringComparer.Ordinal)).ToArray(), positional.Length);
}
void Emit(Type type, bool write)
{
    string id = Id(type), name = Name(type);
    if (type == typeof(Version))
    {
        if (write) schema.AppendLine("System.Version:nullable scalar-components-v1");
        code.Append(write
            ? "    internal void Version(global::System.Version? value)\n    {\n        Boolean(value is not null); if (value is null) return;\n        using var scope = EnterValue();\n        Int32(value.Major); Int32(value.Minor); Int32(value.Build); Int32(value.Revision);\n    }\n"
            : "    internal global::System.Version? Version()\n    {\n        if (!Boolean()) return null;\n        using var scope = EnterValue();\n        int major = Int32(), minor = Int32(), build = Int32(), revision = Int32();\n        if (major < 0 || minor < 0 || build < -1 || revision < -1 || build == -1 && revision != -1)\n            throw new global::System.IO.InvalidDataException(\"Invalid service version components.\");\n        return build == -1 ? new global::System.Version(major, minor)\n            : revision == -1 ? new global::System.Version(major, minor, build)\n            : new global::System.Version(major, minor, build, revision);\n    }\n");
        return;
    }
    if (Special(type) && !type.IsEnum) { if (write) schema.AppendLine(type.FullName + ":scalar"); return; }
    if (type.IsEnum)
    {
        if (Enum.GetUnderlyingType(type) != typeof(int)) throw new InvalidOperationException("Unsupported enum storage: " + type);
        int[] values = Enum.GetValues(type).Cast<object>().Select(Convert.ToInt32).Distinct().ToArray();
        if (write) schema.AppendLine(type.FullName + ":" + string.Join(',', Enum.GetValues(type).Cast<object>().Select(value => value + "=" + Convert.ToInt32(value))));
        string valid = type.IsDefined(typeof(FlagsAttribute)) ? $"(value & ~{values.Aggregate(0, (mask, value) => mask | value)}) == 0" : "value is " + string.Join(" or ", values);
        code.Append(write ? $"    internal void {id}({name} value) => Int32((int)value);\n"
            : $"    internal {name} {id}() {{ int value = Int32(); return {valid} ? ({name})value : throw new global::System.IO.InvalidDataException(\"Invalid service enum.\"); }}\n");
        return;
    }
    string optional = type.IsValueType ? "" : "?";
    code.Append(write ? $"    internal void {id}({name}{optional} value)\n    {{\n" : $"    internal {name}{optional} {id}()\n    {{\n");
    if (Nullable.GetUnderlyingType(type) is { } underlying)
    {
        if (write) schema.AppendLine(id + ":nullable " + Id(underlying));
        code.Append(write ? $"        Boolean(value.HasValue); if (value.HasValue) {Id(underlying)}(value.Value);\n"
            : $"        return Boolean() ? {Id(underlying)}() : null;\n");
    }
    else if (StringMap(type))
    {
        if (write) schema.AppendLine(id + ":map String=String");
        code.Append(write ? "        if (value is null) { Int32(-1); return; }\n        using var scope = EnterValue();\n        Count(value.Count);\n        foreach (var item in value) { String(item.Key); String(item.Value); }\n"
            : "        int count = Count(); if (count == -1) return null;\n        using var scope = EnterValue();\n        var value = new global::System.Collections.Generic.Dictionary<string, string>(count, global::System.StringComparer.Ordinal);\n        for (int index = 0; index < count; index++)\n        {\n            string key = String() ?? throw new global::System.IO.InvalidDataException(\"Missing service map key.\");\n            string item = String() ?? throw new global::System.IO.InvalidDataException(\"Missing service map value.\");\n            if (!value.TryAdd(key, item)) throw new global::System.IO.InvalidDataException(\"Duplicate service map key.\");\n        }\n        return new global::System.Collections.ObjectModel.ReadOnlyDictionary<string, string>(value);\n");
    }
    else if (TypedMap(type))
    {
        Type key = type.GetGenericArguments()[0], value = type.GetGenericArguments()[1];
        if (write) schema.AppendLine(id + ":map " + Id(key) + "=" + Id(value));
        string comparer = key == typeof(string) ? ", global::System.StringComparer.Ordinal" : "";
        string missingKey = key.IsValueType ? "" : " ?? throw new global::System.IO.InvalidDataException(\"Missing service map key.\")";
        string missingValue = value.IsValueType ? "" : " ?? throw new global::System.IO.InvalidDataException(\"Missing service map value.\")";
        code.Append(write
            ? $"        if (value is null) {{ Int32(-1); return; }}\n        using var scope = EnterValue();\n        Count(value.Count);\n        foreach (var item in value) {{ {Id(key)}(item.Key); {Id(value)}(item.Value); }}\n"
            : $"        int count = Count(); if (count == -1) return null;\n        using var scope = EnterValue();\n        var value = new global::System.Collections.Generic.Dictionary<{Name(key)}, {Name(value)}>(count{comparer});\n        for (int index = 0; index < count; index++)\n        {{\n            var key = {Id(key)}(){missingKey};\n            var item = {Id(value)}(){missingValue};\n            if (!value.TryAdd(key, item)) throw new global::System.IO.InvalidDataException(\"Duplicate service map key.\");\n        }}\n        return new global::System.Collections.ObjectModel.ReadOnlyDictionary<{Name(key)}, {Name(value)}>(value);\n");
    }
    else if (Element(type) is { } element)
    {
        if (write) schema.AppendLine(id + ":list " + Id(element));
        code.Append(write ? $"        if (value is null) {{ Int32(-1); return; }}\n        using var scope = EnterValue();\n        Count(value.{(type.IsArray ? "Length" : "Count")});\n        foreach (var item in value) {Id(element)}(item);\n"
            : $"        int count = Count(); if (count == -1) return null;\n        using var scope = EnterValue();\n        var value = new {Name(element)}[count];\n        for (int index = 0; index < count; index++) value[index] = {Id(element)}(){(!element.IsValueType ? " ?? throw new global::System.IO.InvalidDataException(\"Missing service item.\")" : "")};\n        return value;\n");
    }
    else
    {
        var shape = Shape(type);
        // Generic Type.FullName embeds the argument assemblies' release versions.
        if (write) schema.AppendLine(type.FullName + ":" + string.Join(',', shape.Properties.Select(p => p.Name + "=" + Name(p.PropertyType) + ":" + nullability.Create(p).ReadState)));
        if (!type.IsValueType) code.Append(write ? "        Boolean(value is not null); if (value is null) return;\n" : "        if (!Boolean()) return null;\n");
        code.Append("        using var scope = EnterValue();\n");
        if (write) foreach (var property in shape.Properties) code.Append($"        {Id(property.PropertyType)}(value.{property.Name});\n");
        else
        {
            for (int index = 0; index < shape.Properties.Length; index++)
            {
                var property = shape.Properties[index];
                code.Append($"        var p{index} = {Id(property.PropertyType)}()" + (!property.PropertyType.IsValueType && nullability.Create(property).ReadState == NullabilityState.NotNull
                    ? " ?? throw new global::System.IO.InvalidDataException(\"Missing service field.\");\n" : ";\n"));
            }
            code.Append($"        return new {name}(" + string.Join(", ", Enumerable.Range(0, shape.Positional).Select(index => "p" + index + (!shape.Properties[index].PropertyType.IsValueType ? "!" : ""))) + ")");
            if (shape.Positional != shape.Properties.Length) code.Append(" { " + string.Join(", ", Enumerable.Range(shape.Positional, shape.Properties.Length - shape.Positional)
                .Select(index => shape.Properties[index].Name + " = p" + index + (!shape.Properties[index].PropertyType.IsValueType ? "!" : ""))) + " }");
            code.Append(";\n");
        }
    }
    code.Append("    }\n");
}
