static (ConstructorInfo Constructor, PropertyInfo[] Properties, PropertyInfo[] Extras) Shape(Type t)
{
    PropertyInfo[] props = t.GetProperties(BindingFlags.Instance | BindingFlags.Public).Where(p => p.GetIndexParameters().Length == 0).ToArray();
    var ctor = t.GetConstructors().Where(c => c.GetParameters().All(p => props.Any(v => string.Equals(v.Name, p.Name, StringComparison.OrdinalIgnoreCase) && p.ParameterType.IsAssignableFrom(v.PropertyType))))
        .OrderByDescending(c => c.GetParameters().Length).FirstOrDefault() ?? throw new InvalidOperationException("No DTO constructor: " + t);
    var positional = ctor.GetParameters().Select(p => props.Single(v => string.Equals(v.Name, p.Name, StringComparison.OrdinalIgnoreCase))).ToArray();
    var extras = props.Where(p => p.SetMethod is { IsPublic: true } && !positional.Contains(p)).OrderBy(p => p.Name, StringComparer.Ordinal).ToArray();
    return (ctor, positional.Concat(extras).ToArray(), extras);
}
void Emit(Type t, bool write)
{
    string id = Id(t), name = Name(t);
    if (Special(t))
    {
        if (write) schema.AppendLine(id + ":" + (t.IsEnum ? string.Join(',', Enum.GetValues(t).Cast<object>().Select(v => v + "=" + Convert.ToInt64(v))) : "scalar"));
        if (!t.IsEnum) return;
        if (Enum.GetUnderlyingType(t) != typeof(int)) throw new InvalidOperationException("Unsupported enum storage: " + t);
        var values = Enum.GetValues(t).Cast<object>().Select(Convert.ToInt32).Distinct().ToArray();
        string valid = t.IsDefined(typeof(FlagsAttribute))
            ? $"(value & ~{values.Aggregate(0, (mask, v) => mask | v)}) == 0"
            : "value is " + string.Join(" or ", values);
        code.Append(write ? $"    internal void {id}({name} value) => Int32((int)value);\n" :
            $"    internal {name} {id}() {{ int value = Int32(); return {valid} ? ({name})value : throw new global::System.IO.InvalidDataException(\"Invalid wire enum.\"); }}\n");
        return;
    }
    string optional = !t.IsValueType ? "?" : "";
    code.Append(write ? $"    internal void {id}({name}{optional} value)\n    {{\n" : $"    internal {name}{optional} {id}()\n    {{\n");
    if (Nullable.GetUnderlyingType(t) is { } underlying)
    {
        code.Append(write ? $"        Boolean(value.HasValue); if (value.HasValue) {Id(underlying)}(value.Value);\n" : $"        return Boolean() ? {Id(underlying)}() : null;\n");
    }
    else if (Element(t) is { } element)
    {
        if (write)
            code.Append($"        if (value is null) {{ Int32(-1); return; }}\n        Count(value.{(t.IsArray ? "Length" : "Count")});\n        foreach (var item in value) {Id(element)}(item);\n");
        else
            code.Append($"        int count = Count(); if (count == -1) return null;\n        var result = new {Name(element)}[count];\n        for (int i = 0; i < count; i++) result[i] = {Id(element)}(){(!element.IsValueType ? " ?? throw new global::System.IO.InvalidDataException(\"Null wire collection item.\")" : "")};\n        return result;\n");
    }
    else
    {
        var shape = Shape(t);
        if (write) schema.AppendLine(id + ":" + string.Join(',', shape.Properties.Select(p => p.Name + "=" + Id(p.PropertyType) + ":" + nullability.Create(p).ReadState + ":" + FieldMethod(t, p))));
        if (!t.IsValueType) code.Append(write ? "        Boolean(value is not null); if (value is null) return;\n" : "        if (!Boolean()) return null;\n");
        if (write)
            foreach (var p in shape.Properties) code.Append($"        {FieldMethod(t, p)}(value.{p.Name});\n");
        else
        {
            for (int i = 0; i < shape.Properties.Length; i++)
                code.Append($"        var p{i} = {FieldMethod(t, shape.Properties[i])}()" +
                    (!shape.Properties[i].PropertyType.IsValueType && nullability.Create(shape.Properties[i]).ReadState == NullabilityState.NotNull
                        ? " ?? throw new global::System.IO.InvalidDataException(\"Missing required wire field.\");\n" : ";\n"));
            int positional = shape.Properties.Length - shape.Extras.Length;
            code.Append($"        return new {name}(" + string.Join(", ", Enumerable.Range(0, positional).Select(i => "p" + i + (!shape.Properties[i].PropertyType.IsValueType ? "!" : ""))) + ")");
            if (shape.Extras.Length > 0) code.Append(" { " + string.Join(", ", Enumerable.Range(positional, shape.Extras.Length).Select(i => shape.Properties[i].Name + " = p" + i + (!shape.Properties[i].PropertyType.IsValueType ? "!" : ""))) + " }");
            code.Append(";\n");
        }
    }
