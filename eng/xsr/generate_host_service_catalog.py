"""Pin native Host admission to the generated business service schemas."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def fingerprint(path):
    return re.search(r'Fingerprint = "([A-F0-9]{64})"', (ROOT / path).read_text())[1]


def generate():
    accounts = fingerprint("native/AccountsProtocol/ServiceWire.Generated.cs") + "/" + fingerprint("native/AccountsProtocol/AccountRouteSchema.Generated.cs")
    entries = [(1, "accounts", "nexa_accounts", "nexa-accounts/1/" + accounts)]
    for number, name in [(2, "Network"), (3, "Minecraft"), (4, "Updates")]:
        schema = fingerprint("native/" + name + "ServiceProtocol/ServiceWire.Generated.cs")
        identity = "nexa-" + name.lower() + "-service/1/" + ("error-envelope-1/" if number >= 3 else "") + schema
        entries.append((number, name.lower(), "nexa_" + name.lower() + "_service", identity))
    digest = hashlib.sha256("\n".join("|".join(map(str, entry)) for entry in entries).encode()).hexdigest().upper()
    lines = ['// <auto-generated/>', 'namespace Nexa.Native.Host.Services;', '',
             'internal readonly record struct HostServiceDescriptor(int Id, string Name, string Prefix, string Identity);', '',
             'internal static class HostServiceCatalog', '{',
             f'    internal const string Identity = "nexa-host-services/1/{digest}";',
             f'    internal const string UiIdentity = "nexa-ui/3/{digest}";',
             '    internal static HostServiceDescriptor Get(int id) => id switch', '    {']
    for number, name, prefix, identity in entries:
        lines.append(f'        {number} => new({number}, "{name}", "{prefix}", "{identity}"),')
    lines.extend(['        _ => throw new ArgumentOutOfRangeException(nameof(id)),', '    };', '}', ''])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "native/HostServiceProtocol/HostServiceCatalog.Generated.cs"
    content = generate()
    if args.check:
        if output.read_text() != content:
            raise SystemExit("Host service catalog is stale; regenerate and review admission identities")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(content)
